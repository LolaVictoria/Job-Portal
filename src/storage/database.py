import os

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

load_dotenv()

def get_connection():
    """Connect to the Neon PostgreSQL database."""
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is not set. Configure your Neon connection string."
        )

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
    )


def initialize_database():
    """Create the jobs table, outbox table, and indexes."""
    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS jobs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source TEXT NOT NULL,
                source_job_id TEXT NOT NULL,
                company TEXT NOT NULL,
                title TEXT NOT NULL,
                location TEXT NOT NULL,
                url TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                notification_status TEXT NOT NULL DEFAULT 'PENDING',
                UNIQUE(source, source_job_id)
            )
        """)

        connection.execute("""
            ALTER TABLE jobs
            ADD COLUMN IF NOT EXISTS notification_status
            TEXT NOT NULL DEFAULT 'PENDING'
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS email_outbox (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                job_id BIGINT NOT NULL UNIQUE REFERENCES jobs(id),
                status TEXT NOT NULL DEFAULT 'PENDING',
                attempts INTEGER NOT NULL DEFAULT 0,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                sent_at TIMESTAMPTZ,
                last_error TEXT
            )
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_outbox_status
            ON email_outbox(status)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_jobs_notification_status
            ON jobs(notification_status)
        """)


def save_job(job: dict) -> bool:
    """Save a new job and its outbox entry atomically."""
    with get_connection() as connection:
        cursor = connection.execute("""
            INSERT INTO jobs (
                source,
                source_job_id,
                company,
                title,
                location,
                url
            )
            VALUES (%s, %s, %s, %s, %s, %s)
            ON CONFLICT (source, source_job_id) DO NOTHING
            RETURNING id
        """, (
            job["source"],
            job["source_job_id"],
            job["company"],
            job["title"],
            job["location"],
            job["url"],
        ))

        saved_job = cursor.fetchone()

        if saved_job is None:
            return False

        connection.execute("""
            INSERT INTO email_outbox (job_id)
            VALUES (%s)
        """, (saved_job["id"],))

        return True


def get_saved_jobs() -> list[dict]:
    """Return all saved jobs."""
    with get_connection() as connection:
        rows = connection.execute("""
            SELECT *
            FROM jobs
            ORDER BY created_at DESC
        """).fetchall()

        return [dict(row) for row in rows]


def get_pending_jobs() -> list[dict]:
    """Return jobs awaiting notification using the legacy status."""
    with get_connection() as connection:
        rows = connection.execute("""
            SELECT *
            FROM jobs
            WHERE notification_status = 'PENDING'
            ORDER BY created_at ASC
        """).fetchall()

        return [dict(row) for row in rows]


def mark_job_as_sent(job_id: int) -> None:
    """Mark a job as notified using the legacy workflow."""
    with get_connection() as connection:
        connection.execute("""
            UPDATE jobs
            SET notification_status = 'SENT'
            WHERE id = %s
        """, (job_id,))


def get_pending_outbox_jobs() -> list[dict]:
    """Return jobs with pending outbox notifications."""
    with get_connection() as connection:
        rows = connection.execute("""
            SELECT
                email_outbox.id AS outbox_id,
                jobs.id AS job_id,
                jobs.source,
                jobs.source_job_id,
                jobs.company,
                jobs.title,
                jobs.location,
                jobs.url,
                jobs.created_at
            FROM email_outbox
            JOIN jobs ON jobs.id = email_outbox.job_id
            WHERE email_outbox.status = 'PENDING'
            ORDER BY email_outbox.created_at ASC
        """).fetchall()

        return [dict(row) for row in rows]


def mark_outbox_as_sent(outbox_ids: list[int]) -> None:
    """Mark outbox entries and their jobs as sent."""
    if not outbox_ids:
        return

    with get_connection() as connection:
        connection.execute("""
            UPDATE email_outbox
            SET status = 'SENT',
                sent_at = CURRENT_TIMESTAMP,
                last_error = NULL
            WHERE id = ANY(%s)
        """, (outbox_ids,))

        connection.execute("""
            UPDATE jobs
            SET notification_status = 'SENT'
            WHERE id IN (
                SELECT job_id
                FROM email_outbox
                WHERE id = ANY(%s)
            )
        """, (outbox_ids,))


def record_outbox_failure(
    outbox_ids: list[int],
    error: str,
) -> None:
    """Record a failed attempt and leave entries pending for retry."""
    if not outbox_ids:
        return

    with get_connection() as connection:
        connection.execute("""
            UPDATE email_outbox
            SET attempts = attempts + 1,
                last_error = %s
            WHERE id = ANY(%s)
              AND status = 'PENDING'
        """, (error[:1000], outbox_ids))